import { createHash, randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, rename, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { Readable } from 'node:stream';

/**
 * Private file storage behind an adapter (D5): business code only knows opaque storage keys.
 * The local adapter can later be replaced by an S3-compatible one without touching the routes.
 */
export interface FileStorage {
  put(key: string, bytes: Buffer): Promise<void>;
  read(key: string): Readable;
  exists(key: string): Promise<boolean>;
}

const KEY = /^[0-9a-f]{2}\/[0-9a-f]{64}$/;

export class LocalDiskStorage implements FileStorage {
  constructor(private readonly root: string) {}

  private pathFor(key: string): string {
    // Keys are generated by the server and validated: no client-supplied path ever reaches the disk.
    if (!KEY.test(key)) throw new Error('Invalid storage key');
    return path.join(this.root, key);
  }

  async put(key: string, bytes: Buffer): Promise<void> {
    const target = this.pathFor(key);
    await mkdir(path.dirname(target), { recursive: true });
    const tmp = `${target}.tmp-${randomUUID()}`;
    await writeFile(tmp, bytes, { flag: 'wx', mode: 0o600 });
    await rename(tmp, target); // atomic: a reader never sees a half-written file
  }

  read(key: string): Readable {
    return createReadStream(this.pathFor(key));
  }

  async exists(key: string): Promise<boolean> {
    try {
      await stat(this.pathFor(key));
      return true;
    } catch {
      return false;
    }
  }
}

export const ALLOWED_TYPES = ['image/jpeg', 'image/png', 'image/webp', 'application/pdf'] as const;
export type AllowedType = (typeof ALLOWED_TYPES)[number];

/** Detects the real type from the first bytes; the browser's declared type is never trusted alone. */
export function detectType(bytes: Buffer): AllowedType | null {
  if (bytes.length >= 3 && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) return 'image/jpeg';
  if (bytes.length >= 8 && bytes.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return 'image/png';
  if (bytes.length >= 12 && bytes.subarray(0, 4).toString('latin1') === 'RIFF' && bytes.subarray(8, 12).toString('latin1') === 'WEBP') return 'image/webp';
  if (bytes.length >= 5 && bytes.subarray(0, 5).toString('latin1') === '%PDF-') return 'application/pdf';
  return null;
}

export function sha256Hex(bytes: Buffer): string {
  return createHash('sha256').update(bytes).digest('hex');
}

/** Content-addressed key: identical bytes are stored once. */
export function keyFor(sha: string): string {
  return `${sha.slice(0, 2)}/${sha}`;
}

/** Display-only file name: no path parts, no control characters, bounded length. */
export function sanitizeName(raw: string | undefined): string | null {
  if (!raw) return null;
  let name: string;
  try {
    name = decodeURIComponent(raw);
  } catch {
    name = raw;
  }
  name = name.split(/[\\/]/).pop() ?? '';
  // Control characters are removed on purpose (display-only name, never a path).
  // eslint-disable-next-line no-control-regex
  name = name.replace(/[\u0000-\u001f\u007f<>:"|?*]/g, '').trim().slice(0, 200);
  return name || null;
}
